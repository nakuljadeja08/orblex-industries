"""
report_writer_agent.py — Claude-powered Report Writer Agent.

Synthesizes the full pipeline output (Analyst → Risk → Allocator)
into a structured, human-readable JSON report for audit and review.
"""

import json
import logging
from typing import Optional

from anthropic import Anthropic

from llm import ask

logger = logging.getLogger(__name__)

# Model and per-model request rules: llm.py.

SYSTEM_PROMPT = """You are the Report Writer at Orblex Industries, an autonomous AI-powered portfolio management system.

Your job is to synthesize the outputs of three upstream agents — the Analyst, the Risk Manager, and the Portfolio Allocator — into a single, structured, human-readable investment report.

This report is NOT for trading execution. It is an auditable record of what the system decided, why, and how confident it is. Transparency and explainability are the top priorities.

You will receive:
- Portfolio-level metadata: report date, market risk level, invested %, cash %
- A strategy note from the Allocator
- A risk summary from the Risk Manager
- Per-ticker data: signal, strength, analyst summary, risk score, risk flags, allocation %, rationale, anomalies

Your output MUST be a single valid JSON object with exactly these fields:

{
  "executive_summary": "<3-4 sentence high-level summary of the full pipeline decision — what the market looks like, what the system did, and why>",
  "market_outlook": "<2-3 sentence assessment of the current market environment based on risk signals>",
  "portfolio_stance": "AGGRESSIVE" | "BALANCED" | "DEFENSIVE" | "CASH_HEAVY",
  "key_themes": ["<theme 1>", "<theme 2>", "<theme 3>"],
  "confidence_level": "HIGH" | "MODERATE" | "LOW",
  "confidence_reasoning": "<1-2 sentences explaining confidence level based on signal agreement and anomaly count>",
  "ticker_narratives": [
    {
      "ticker": "AAPL",
      "one_liner": "<Single sentence: signal + key reason + allocation outcome>",
      "full_narrative": "<2-3 sentences: analyst view, risk assessment, and final allocation rationale combined>"
    }
  ],
  "risk_highlights": "<2-3 sentences on the most important risk factors flagged this cycle>",
  "anomaly_digest": "<1-2 sentences summarizing any anomalies detected — or 'No significant anomalies detected this cycle.' if none>",
  "watchdog_notes": "<Any internal consistency issues or concerns the downstream Watchdog should verify — or 'None.' if clean>",
  "disclaimer": "This report is generated by an autonomous AI system for research and simulation purposes only. It does not constitute financial advice."
}

Rules:
- Output ONLY the JSON. No preamble, no markdown fences, no commentary.
- portfolio_stance: when PORTFOLIO OVERVIEW gives a stance "set by rule", use exactly that label.
  The rules behind it (and the ones to apply if none is given):
  - AGGRESSIVE: majority BUY signals, LOW market risk, cash < 10%
  - BALANCED: mixed signals or MODERATE risk
  - DEFENSIVE: HIGH market risk OR >30% flagged tickers
  - CASH_HEAVY: CRITICAL market risk OR cash > 25%
- confidence_level rules:
  - HIGH: >70% signal agreement (all BUY or all HOLD), <2 anomalies total
  - MODERATE: mixed signals but consistent risk assessment
  - LOW: contradicting signals, high anomaly count, or CRITICAL market risk
- key_themes: 3 short themes that capture the narrative (e.g. "Momentum divergence in tech", "Elevated volatility regime")
- watchdog_notes: flag if allocated_pct + cash_pct ≠ 100, if SELL tickers got non-zero allocation, or any other internal inconsistency
- For any ticker that is EXCLUDED (allocated_pct = 0%) AND carries an ANOMALY_CLUSTER or HIGH_VOLATILITY flag AND has risk_score >= 8, include a brief note in watchdog_notes explaining why it was excluded. Do not leave watchdog_notes as "None." when high-risk anomalous tickers are present in the portfolio universe.
"""


def _rule_stance(ctx: dict):
    from portfolio_stance import stance
    t = ctx.get("ticker_summaries") or []
    return stance(ctx.get("market_risk_level"), ctx.get("cash_pct"), len(ctx.get("flagged_tickers") or []),
                  len(t), sum(1 for x in t if x.get("signal") == "BUY"))


def _build_prompt(ctx: dict) -> str:
    ticker_lines = []
    for t in ctx["ticker_summaries"]:
        flags      = ", ".join(t["risk_flags"]) if t["risk_flags"] else "none"
        anomalies  = t.get("anomalies", [])
        anom_count = len(anomalies) if isinstance(anomalies, list) else 0
        ticker_lines.append(
            f"  {t['ticker']:6s}  signal={t['signal']:4s} ({t['signal_strength']:8s})  "
            f"risk_score={t['risk_score']:2d}  allocated={t['allocated_pct']:5.1f}%  "
            f"flags=[{flags}]  anomalies={anom_count}\n"
            f"    analyst_summary: {t['analyst_summary'][:120] if t['analyst_summary'] else 'n/a'}\n"
            f"    alloc_rationale: {t['allocation_rationale'][:120] if t['allocation_rationale'] else 'n/a'}"
        )

    tickers_block = "\n".join(ticker_lines)

    total_check = sum(t["allocated_pct"] for t in ctx["ticker_summaries"]) + ctx["cash_pct"]

    return f"""Generate the Orblex Industries Investment Report for {ctx['report_date']}.

PIPELINE RUN IDs
----------------
Analyst run   : {ctx['analyst_run_id']}
Risk run      : {ctx['risk_run_id']}
Allocator run : {ctx['alloc_run_id']}

PORTFOLIO OVERVIEW
------------------
Market risk level  : {ctx['market_risk_level']}
Concentration risk : {ctx['concentration_risk']}
Volatility risk    : {ctx['volatility_risk']}
Invested           : {ctx['invested_pct']}%
Cash               : {ctx['cash_pct']}%
Total check        : {round(total_check, 2)}% (should be 100.0)
Flagged tickers    : {ctx['flagged_tickers'] or 'none'}
Portfolio stance   : {_rule_stance(ctx) or 'apply the stance rules'}  (set by rule; use exactly this label and write consistently with it)

RISK SUMMARY (from Risk Manager)
---------------------------------
{ctx['risk_summary'] or 'Not available.'}

STRATEGY NOTE (from Allocator)
-------------------------------
{ctx['strategy_note'] or 'Not available.'}

PER-TICKER DATA
---------------
{tickers_block}

Generate the full report JSON now."""


def write_report(ctx: dict) -> Optional[dict]:
    """
    Calls Claude Report Writer Agent and returns a parsed report dict.
    Returns None on failure.
    """
    client = Anthropic()
    prompt = _build_prompt(ctx)

    logger.info("  Calling Claude Report Writer Agent...")

    try:
        msg = ask("decision", SYSTEM_PROMPT, prompt, 8192, client)
    except Exception as e:
        logger.error(f"  Anthropic API error: {e}")
        return None

    raw = msg.text.strip()

    # Strip accidental markdown fences
    if raw.startswith("```"):
        raw = raw.split("```")[1]
        if raw.startswith("json"):
            raw = raw[4:]
        raw = raw.strip()

    try:
        result = json.loads(raw)
    except json.JSONDecodeError as e:
        logger.error(f"  Failed to parse agent JSON: {e}\nRaw output:\n{raw}")
        return None

    result["prompt_tokens"] = msg.input_tokens
    result["output_tokens"] = msg.output_tokens
    result["model"]         = msg.model

    return result
